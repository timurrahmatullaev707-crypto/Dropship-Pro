let currentLanguage = localStorage.getItem('valmora_lang') || 'uz';

function setLanguage(lang) {
    if (!VALMORA_I18N[lang]) lang = 'uz';
    currentLanguage = lang;
    localStorage.setItem('valmora_lang', lang);
    applyTranslations();

    // Sync all language dropdowns on page
    document.querySelectorAll('.language-select').forEach(sel => {
        sel.value = lang;
    });

    // Re-render storefront products if present
    if (typeof window.renderProducts === 'function') {
        window.renderProducts();
    }
    // Re-render admin products if present
    if (typeof window.renderProductsGrid === 'function') {
        window.renderProductsGrid();
    }
    // Re-render orders if present
    if (typeof window.renderOrdersPage === 'function') {
        window.renderOrdersPage();
    }
}

function getTranslation(key, fallback = '') {
    const dict = VALMORA_I18N[currentLanguage] || VALMORA_I18N.uz;
    return dict[key] || VALMORA_I18N.uz[key] || fallback || key;
}

function applyTranslations() {
    const dict = VALMORA_I18N[currentLanguage] || VALMORA_I18N.uz;

    // Translate standard text nodes
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            el.innerHTML = dict[key];
        }
    });

    // Translate input placeholders
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
        const key = el.getAttribute('data-i18n-ph');
        if (dict[key]) {
            el.setAttribute('placeholder', dict[key]);
        }
    });

    document.documentElement.setAttribute('lang', currentLanguage);
}

document.addEventListener('DOMContentLoaded', () => {
    // Attach listener to any language selector dropdown
    document.querySelectorAll('.language-select').forEach(sel => {
        sel.value = currentLanguage;
        sel.addEventListener('change', (e) => {
            setLanguage(e.target.value);
            if (window.sound && typeof window.sound.playClick === 'function') {
                window.sound.playClick();
            }
        });
    });

    applyTranslations();
});
